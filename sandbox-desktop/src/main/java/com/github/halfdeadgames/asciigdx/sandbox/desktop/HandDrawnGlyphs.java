    private static boolean[][] art(String... rows) {
        if (rows.length != SIZE) {
            throw new IllegalArgumentException("Hand-drawn glyph needs " + SIZE + " rows: " + rows.length);
        }
        boolean[][] pixels = new boolean[SIZE][SIZE];
        for (int y = 0; y < SIZE; y++) {
            if (rows[y].length() != SIZE) {
                throw new IllegalArgumentException(
                    "Hand-drawn glyph row " + y + " needs " + SIZE + " columns: " + rows[y].length());
            }
            for (int x = 0; x < SIZE; x++) {
                pixels[y][x] = rows[y].charAt(x) == '#';
            }
        }
        return pixels;
    }

package com.github.halfdeadgames.asciigdx.ui;

/** Where a widget sits horizontally inside the free space of its {@link TableCell}. */
public enum HorizontalAlignment {
    /** The widget touches the left edge of the cell's area. */
    LEFT,
    /** The widget is centered; an odd leftover cell goes to the right side. */
    CENTER,
    /** The widget touches the right edge of the cell's area. */
    RIGHT
}

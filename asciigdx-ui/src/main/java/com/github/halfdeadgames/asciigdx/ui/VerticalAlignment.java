package com.github.halfdeadgames.asciigdx.ui;

/** Where a widget sits vertically inside the free space of its {@link TableCell}. */
public enum VerticalAlignment {
    /** The widget touches the top edge of the cell's area. */
    TOP,
    /** The widget is centered; an odd leftover row goes below the widget. */
    CENTER,
    /** The widget touches the bottom edge of the cell's area. */
    BOTTOM
}

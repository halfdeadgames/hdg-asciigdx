package com.github.halfdeadgames.asciigdx.ui;

/** The two fonts a {@link UiSurface} draws with. */
public enum UiFont {
    /** The tall font: each glyph is one UI column wide and two UI rows high. */
    TALL,
    /** The square font: each glyph is one UI column wide and one UI row high. */
    SQUARE
}
